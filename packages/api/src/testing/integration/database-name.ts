/**
 * Naming of the throwaway databases created by the integration harness (pure helpers).
 *
 * Every `pnpm test:integration` run creates its own database on the server of
 * `TEST_DATABASE_URL`, so parallel runs (other developers, other packages, CI retries) never
 * share data. The prefix also guarantees the harness only ever drops databases it created.
 */
export const INTEGRATION_DATABASE_PREFIX = "farmacias_api_it_";

const DATABASE_NAME_PATTERN = /^farmacias_api_it_[a-z0-9_]{1,40}$/;

/** `farmacias_api_it_<epoch ms base36>_<random hex>`: unique, lowercase, a valid identifier. */
export function createIntegrationDatabaseName(nowMs: number, randomHex: string): string {
  return `${INTEGRATION_DATABASE_PREFIX}${nowMs.toString(36)}_${randomHex.toLowerCase()}`;
}

/**
 * Throws unless `name` is a database name generated by `createIntegrationDatabaseName`.
 * `CREATE/DROP DATABASE` cannot take bind parameters, so the name is checked before it is
 * interpolated into SQL (it never comes from user input).
 */
export function assertIntegrationDatabaseName(name: string): string {
  if (!DATABASE_NAME_PATTERN.test(name)) {
    throw new Error(`Refusing to use "${name}": not an integration test database name.`);
  }
  return name;
}

/** Same server, user and options as `serverUrl`, pointed at the database `name`. */
export function withDatabaseName(serverUrl: string, name: string): string {
  const url = new URL(serverUrl);
  url.pathname = `/${assertIntegrationDatabaseName(name)}`;
  return url.toString();
}

/** Database name of a PostgreSQL URL (`/app` → `app`). */
export function databaseNameOf(databaseUrl: string): string {
  return decodeURIComponent(new URL(databaseUrl).pathname.replace(/^\//, ""));
}
